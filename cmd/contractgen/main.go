// contractgen writes Go-owned boundary artifacts, or verifies drift without
// modifying any output when -check is supplied. Run from the module root.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/localswim/localswim/internal/contract"
	"github.com/localswim/localswim/internal/contract/archive"
	"github.com/localswim/localswim/internal/contract/transport"
)

func main() {
	check := flag.Bool("check", false, "fail on generated drift without writing outputs")
	root := flag.String("root", ".", "repository output root")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "unexpected arguments")
		os.Exit(2)
	}
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run(root string, check bool) error {
	files, e := contract.GeneratedFiles()
	if e != nil {
		return e
	}
	archiveFiles, e := archive.GeneratedFiles()
	if e != nil {
		return e
	}
	transportFiles, e := transport.GeneratedFiles()
	if e != nil {
		return e
	}
	for _, bundle := range []struct {
		name string
		data map[string][]byte
	}{{"archive", archiveFiles}, {"transport", transportFiles}} {
		for name, data := range bundle.data {
			if filepath.IsAbs(name) || filepath.ToSlash(filepath.Clean(name)) != name ||
				strings.Contains(name, "\\") ||
				!(strings.HasPrefix(name, "schemas/"+bundle.name+"/") || strings.HasPrefix(name, "web/generated/"+bundle.name+"/")) {
				return fmt.Errorf("invalid %s output: %s", bundle.name, name)
			}
			if _, exists := files[name]; exists {
				return fmt.Errorf("duplicate generated output: %s", name)
			}
			files[name] = data
		}
	}
	// The browser validator consumes the same Go-owned schemas. Generate its
	// namespace map here so new wire models cannot leave a stale manual snapshot.
	definitions := map[string]any{}
	for _, bundle := range []struct{ name, path string }{
		{"mutation", "schemas/mutation-requests.schema.json"},
		{"archive", "schemas/archive/contracts.schema.json"},
		{"transport", "schemas/transport/contracts.schema.json"},
	} {
		var document struct {
			Definitions map[string]any `json:"$defs"`
		}
		if err := json.Unmarshal(files[bundle.path], &document); err != nil {
			return err
		}
		for name, definition := range document.Definitions {
			if err := qualifyRefs(definition, bundle.name); err != nil {
				return err
			}
			definitions[bundle.name+":"+name] = definition
		}
	}
	encoded, err := json.Marshal(definitions)
	if err != nil {
		return err
	}
	files["web/src/api/schema-data.ts"] = []byte("// Code generated by contractgen. DO NOT EDIT.\nexport const schemas: Record<string, unknown> = " + string(encoded) + ";\n")
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, name := range names {
		path := filepath.Join(root, filepath.FromSlash(name))
		want := files[name]
		if check {
			got, e := os.ReadFile(path)
			if e != nil || !bytes.Equal(got, want) {
				return fmt.Errorf("generated drift: %s", name)
			}
			continue
		}
		if e = os.MkdirAll(filepath.Dir(path), 0755); e != nil {
			return e
		}
		if e = os.WriteFile(path, want, 0644); e != nil {
			return e
		}
	}
	return nil
}

func qualifyRefs(value any, namespace string) error {
	switch value := value.(type) {
	case []any:
		for _, child := range value {
			if err := qualifyRefs(child, namespace); err != nil {
				return err
			}
		}
	case map[string]any:
		for key, child := range value {
			if key != "$ref" {
				if err := qualifyRefs(child, namespace); err != nil {
					return err
				}
				continue
			}
			reference, ok := child.(string)
			if !ok {
				return fmt.Errorf("invalid schema reference")
			}
			prefixes := []struct{ path, name string }{
				{"#/$defs/", namespace},
				{"../archive/contracts.schema.json#/$defs/", "archive"},
				{"../mutation-requests.schema.json#/$defs/", "mutation"},
			}
			matched := false
			for _, prefix := range prefixes {
				if strings.HasPrefix(reference, prefix.path) {
					value[key] = prefix.name + ":" + strings.TrimPrefix(reference, prefix.path)
					matched = true
					break
				}
			}
			if !matched {
				return fmt.Errorf("unsupported schema reference")
			}
		}
	}
	return nil
}
