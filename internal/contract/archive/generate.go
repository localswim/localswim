// GeneratedFiles has no filesystem effects. Callers aggregate these disjoint
// paths with the C01 bundle in the common contractgen command.
func GeneratedFiles() (map[string][]byte, error) {
	defs := map[string]any{}
	var ts strings.Builder
	ts.WriteString("// Code generated by contractgen. DO NOT EDIT.\n// Advisory boundary declarations. Go validation remains authoritative.\n\n")
	generateCommandObjects(defs, &ts)
	defs["ClearInput"] = schemaType(reflect.TypeFor[ClearInput](), true, "")
	fmt.Fprintf(&ts, "export type ClearInput = %s;\n\n", tsType(reflect.TypeFor[ClearInput](), true))
	for _, v := range models {
		t := reflect.TypeOf(v)
		defs[t.Name()] = schemaType(t, true, "")
		fmt.Fprintf(&ts, "export type %s = %s;\n\n", t.Name(), tsType(t, true))
	}
	root := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "D02 archive and recovery boundaries", "$defs": defs, "$comment": "Select a $defs entry. Strict Go decoding, semantic cross-field/reference checks and C/R encoding remain required. No ZIP/native/authority guarantee."}
	b, e := json.MarshalIndent(root, "", "  ")
	if e != nil {
		return nil, e
	}
	b = append(b, '\n')
	return map[string][]byte{"schemas/archive/contracts.schema.json": b, "web/generated/archive/contracts.d.ts": []byte(strings.TrimRight(ts.String(), "\n") + "\n")}, nil
}

func fields(t reflect.Type) []reflect.StructField {
	a := make([]reflect.StructField, t.NumField())
	for i := range a {
		a[i] = t.Field(i)
	}
	sort.Slice(a, func(i, j int) bool { return fieldName(a[i]) < fieldName(a[j]) })
	return a
}
func optionalField(f reflect.StructField) bool {
	return strings.Contains(f.Tag.Get("json"), ",omitempty")
}
func fieldName(f reflect.StructField) string { return strings.Split(f.Tag.Get("json"), ",")[0] }
func schemaType(t reflect.Type, inline bool, format string) map[string]any {
	if t.Kind() == reflect.Pointer {
		return map[string]any{"anyOf": []any{schemaType(t.Elem(), false, format), map[string]any{"type": "null"}}}
	}
	if t == reflect.TypeFor[json.RawMessage]() {
		return map[string]any{"type": "object", "$comment": "Exact command object is validated with the C01 command authority."}
	}
	if t.Kind() == reflect.Struct && !inline {
		return map[string]any{"$ref": "#/$defs/" + t.Name()}
	}
	m := map[string]any{}
	switch t.Kind() {
	case reflect.Struct:
		if t == reflect.TypeFor[Target]() {
			return map[string]any{"oneOf": []any{map[string]any{"type": "object", "properties": map[string]any{"cardId": scalarSchema(reflect.TypeFor[UUID](), "")}, "required": []string{"cardId"}, "additionalProperties": false}, map[string]any{"type": "object", "properties": map[string]any{"grantId": scalarSchema(reflect.TypeFor[UUID](), "")}, "required": []string{"grantId"}, "additionalProperties": false}}}
		}
		p := map[string]any{}
		r := []string{}
		for _, f := range fields(t) {
			n := fieldName(f)
			if name := rawName(t, f); name != "" {
				p[n] = map[string]any{"$ref": "#/$defs/" + name}
			} else {
				p[n] = schemaType(f.Type, false, f.Tag.Get("validate"))
			}
			if !optionalField(f) {
				r = append(r, n)
			}
		}
		m = map[string]any{"type": "object", "properties": p, "required": r, "additionalProperties": false}
		if t == reflect.TypeFor[Preview]() || t == reflect.TypeFor[PreviewRequest]() || t == reflect.TypeFor[Confirmation]() {
			m["allOf"] = []any{map[string]any{"if": map[string]any{"properties": map[string]any{"command": map[string]any{"const": "history.clear"}}}, "then": map[string]any{"properties": map[string]any{"input": map[string]any{"$ref": "#/$defs/ClearInput"}}}, "else": map[string]any{"properties": map[string]any{"input": map[string]any{"$ref": "#/$defs/Retention"}}}}}
		}
	case reflect.Slice:
		m = map[string]any{"type": "array", "items": schemaType(t.Elem(), false, "")}
		if t.Elem() == reflect.TypeFor[UUID]() {
			m["uniqueItems"] = true
			m["x-order"] = "ASCII ascending"
		}
	default:
		m = scalarSchema(t, format)
	}
	return m
}
func scalarSchema(t reflect.Type, format string) map[string]any {
	m := map[string]any{}
	switch t.Kind() {
	case reflect.Bool:
		m["type"] = "boolean"
	case reflect.Uint64:
		m["type"] = "integer"
		m["minimum"] = uint64(0)
		m["maximum"] = uint64(9007199254740991)
		if format == "blob-length" {
			m["maximum"] = 10485760
		}
		if t.Name() == "Positive" {
			m["minimum"] = 1
		}
		if t.Name() == "Version" {
			m["const"] = 1
		}
		if t.Name() == "Days" {
			m["minimum"] = 1
			m["maximum"] = 3650
		}
	case reflect.String:
		m["type"] = "string"
	}
	if e := enums[t.Name()]; len(e) > 0 {
		m["enum"] = e
	}
	switch t.Name() {
	case "UUID":
		m["pattern"] = uuidRE.String()
		m["not"] = map[string]any{"const": "00000000-0000-0000-0000-000000000000"}
	case "Digest":
		m["pattern"] = digestRE.String()
	case "Timestamp":
		m["pattern"] = timeRE.String()
		m["format"] = "date-time"
		m["x-year-minimum"] = 1
	}
	switch format {
	case "title":
		m["minLength"] = 1
		m["maxLength"] = 200
		m["x-nonblank"] = true
	case "comment":
		m["x-nonblank"] = true
		fallthrough
	case "prose":
		m["x-max-utf8-bytes"] = 65536
	case "attachment-name":
		m["x-max-utf8-bytes"] = 255
	case "media-label":
		m["maxLength"] = 127
		m["pattern"] = `^[\x00-\x7f]*$`
	}
	return m
}
func tsType(t reflect.Type, inline bool) string {
	if t.Kind() == reflect.Pointer {
		return tsType(t.Elem(), false) + " | null"
	}
	if t == reflect.TypeFor[json.RawMessage]() {
		return "Readonly<Record<string, unknown>>"
	}
	if t.Kind() == reflect.Struct && !inline {
		return t.Name()
	}
	switch t.Kind() {
	case reflect.Struct:
		if t == reflect.TypeFor[Target]() {
			return "{ readonly cardId: string } | { readonly grantId: string }"
		}
		var b strings.Builder
		b.WriteString("{\n")
		for _, f := range fields(t) {
			fieldType := tsType(f.Type, false)
			if name := rawName(t, f); name != "" {
				fieldType = name
			}
			optional := ""
			if optionalField(f) {
				optional = "?"
			}
			fmt.Fprintf(&b, "  readonly %s%s: %s;\n", fieldName(f), optional, fieldType)
		}
		b.WriteString("}")
		return b.String()
	case reflect.Slice:
		return "ReadonlyArray<" + tsType(t.Elem(), false) + ">"
	case reflect.Bool:
		return "boolean"
	case reflect.Uint64:
		if t.Name() == "Version" {
			return "1"
		}
		return "number"
	case reflect.String:
		if e := enums[t.Name()]; len(e) > 0 {
			a := []string{}
			for _, v := range e {
				a = append(a, fmt.Sprintf("%q", v))
			}
			return strings.Join(a, " | ")
		}
		return "string"
	}
	panic("unsupported declaration")
}

func rawName(parent reflect.Type, f reflect.StructField) string {
	if f.Type != reflect.TypeFor[json.RawMessage]() {
		return ""
	}
	if parent == reflect.TypeFor[FullOutcome]() {
		if f.Name == "Intent" {
			return "Intent"
		}
		return "RetainedResult"
	}
	return "RecoveryInput"
}
func commandSuffix(c contract.Command) string {
	var b strings.Builder
	upper := true
	for _, r := range c {
		if r == '.' || r == '-' {
			upper = true
			continue
		}
		if upper && r >= 'a' && r <= 'z' {
			r -= 32
		}
		upper = false
		b.WriteRune(r)
	}
	return b.String()
}
func generateCommandObjects(defs map[string]any, ts *strings.Builder) {
	ts.WriteString("import type * as Mutation from '../contracts';\n\n")
	inputs := []any{map[string]any{"$ref": "#/$defs/ClearInput"}, map[string]any{"$ref": "#/$defs/Retention"}}
	defs["RecoveryInput"] = map[string]any{"anyOf": inputs}
	ts.WriteString("export type RecoveryInput = ClearInput | Retention;\n\n")
	intents := []any{}
	results := []any{map[string]any{"$ref": "../mutation-requests.schema.json#/$defs/RefusalResult"}}
	intentNames := []string{}
	resultNames := []string{"Mutation.RefusalResult"}
	for _, d := range contract.Commands() {
		name := "Intent" + commandSuffix(d.Command)
		intentNames = append(intentNames, name)
		intents = append(intents, map[string]any{"$ref": "#/$defs/" + name})
		payload := d.Input
		f := map[string]contract.Field{}
		for k, field := range payload.Fields {
			if field.Optional && !contract.PreservesInputOmission(k) {
				n := *field.Type
				n.Nullable = true
				field.Type = &n
				field.Optional = false
			}
			f[k] = field
		}
		payload = &contract.Type{Kind: "object", Fields: f, Variants: d.Input.Variants}
		if d.Recovery {
			payload = &contract.Type{Kind: "object", Fields: map[string]contract.Field{"input": {Type: payload}, "previewHash": {Type: &contract.Type{Kind: "string", Format: "sha256"}}}}
		}
		target := &contract.Type{Kind: "null"}
		cardRev := &contract.Type{Kind: "null"}
		if d.Target != "none" {
			key := "cardId"
			if d.Target == "grant" {
				key = "grantId"
			}
			target = &contract.Type{Kind: "object", Fields: map[string]contract.Field{key: {Type: &contract.Type{Kind: "string", Format: "uuid"}}}}
		}
		if d.Target == "card" {
			cardRev = &contract.Type{Kind: "integer", Min: 1, Max: contract.MaxInteger}
		}
		identity := &contract.Type{Kind: "string", Format: "uuid"}
		version := &contract.Type{Kind: "integer", Min: 1, Max: 1}
		revision := &contract.Type{Kind: "integer", Min: 0, Max: contract.MaxInteger}
		intent := &contract.Type{Kind: "object", Fields: map[string]contract.Field{"fingerprintVersion": {Type: version}, "boardId": {Type: identity}, "incarnation": {Type: identity}, "opId": {Type: identity}, "actorId": {Type: identity}, "command": {Type: &contract.Type{Kind: "string", Enum: []string{string(d.Command)}}}, "target": {Type: target}, "payload": {Type: payload}, "expectedRevision": {Type: revision}, "expectedCardRevision": {Type: cardRev}}}
		defs[name] = descriptorSchema(intent)
		fmt.Fprintf(ts, "export type %s = %s;\n\n", name, descriptorTS(intent))
		result := "Result" + commandSuffix(d.Command)
		results = append(results, map[string]any{"$ref": "../mutation-requests.schema.json#/$defs/" + result})
		resultNames = append(resultNames, "Mutation."+result)
	}
	defs["Intent"] = map[string]any{"anyOf": intents}
	defs["RetainedResult"] = map[string]any{"anyOf": results}
	fmt.Fprintf(ts, "export type Intent = %s;\n\nexport type RetainedResult = %s;\n\n", strings.Join(intentNames, " | "), strings.Join(resultNames, " | "))
}
func descriptorSchema(t *contract.Type) map[string]any {
	if t.Nullable {
		c := *t
		c.Nullable = false
		return map[string]any{"anyOf": []any{descriptorSchema(&c), map[string]any{"type": "null"}}}
	}
	if len(t.Variants) > 0 {
		variants := make([]any, len(t.Variants))
		for i, variant := range t.Variants {
			variants[i] = descriptorSchema(variant)
		}
		return map[string]any{"oneOf": variants}
	}
	if t.Kind == "object" {
		p := map[string]any{}
		r := []string{}
		keys := []string{}
		for k := range t.Fields {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			p[k] = descriptorSchema(t.Fields[k].Type)
			if !t.Fields[k].Optional {
				r = append(r, k)
			}
		}
		return map[string]any{"type": "object", "properties": p, "required": r, "additionalProperties": false}
	}
	if t.Kind == "array" {
		m := map[string]any{"type": "array", "items": descriptorSchema(t.Element)}
		if t.Max > 0 {
			m["maxItems"] = t.Max
		}
		if t.Format == "unique-relationships" {
			m["uniqueItems"] = true
		}
		if t.Format == "sorted-unique" {
			m["uniqueItems"] = true
			m["x-order"] = "ASCII ascending"
		}
		return m
	}
	if t.Kind == "null" {
		return map[string]any{"type": "null"}
	}
	if t.Kind == "integer" {
		return map[string]any{"type": "integer", "minimum": t.Min, "maximum": t.Max}
	}
	if t.Kind == "boolean" {
		return map[string]any{"type": "boolean"}
	}
	typ := reflect.TypeFor[string]()
	switch t.Format {
	case "uuid":
		typ = reflect.TypeFor[UUID]()
	case "sha256":
		typ = reflect.TypeFor[Digest]()
	case "timestamp":
		typ = reflect.TypeFor[Timestamp]()
	}
	m := scalarSchema(typ, t.Format)
	if len(t.Enum) > 0 {
		m["enum"] = t.Enum
	}
	return m
}
func descriptorTS(t *contract.Type) string {
	if t.Nullable {
		c := *t
		c.Nullable = false
		return "(" + descriptorTS(&c) + " | null)"
	}
	if len(t.Variants) > 0 {
		variants := make([]string, len(t.Variants))
		for i, variant := range t.Variants {
			variants[i] = descriptorTS(variant)
		}
		return "(" + strings.Join(variants, " | ") + ")"
	}
	switch t.Kind {
	case "object":
		keys := []string{}
		for k := range t.Fields {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var b strings.Builder
		b.WriteString("{\n")
		for _, k := range keys {
			f := t.Fields[k]
			optional := ""
			if f.Optional {
				optional = "?"
			}
			fmt.Fprintf(&b, "  readonly %s%s: %s;\n", k, optional, descriptorTS(f.Type))
		}
		b.WriteString("}")
		return b.String()
	case "array":
		return "ReadonlyArray<" + descriptorTS(t.Element) + ">"
	case "integer":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "string":
		if len(t.Enum) > 0 {
			a := []string{}
			for _, s := range t.Enum {
				a = append(a, fmt.Sprintf("%q", s))
			}
			return strings.Join(a, " | ")
		}
		return "string"
	}
	panic("unsupported C01 descriptor")
}
