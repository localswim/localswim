package contract

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// GeneratedFiles is deterministic and has no filesystem side effects. Schemas
// describe decoded values: duplicate keys/UTF-8/numeric lexical restrictions must
// still be enforced by DecodeJSON. Declarations never confer runtime authority.
func GeneratedFiles() (map[string][]byte, error) {
	defs := map[string]any{}
	var ts strings.Builder
	ts.WriteString("// Code generated by contractgen. DO NOT EDIT.\n// Boundary types only; Go validation and admission remain authoritative.\n\n")
	var names []string
	for _, d := range Commands() {
		name := typeName(d.Command)
		names = append(names, name)
		t := RequestType(d)
		defs[name] = schema(t)
		fmt.Fprintf(&ts, "export type %s = %s;\n\n", name, declaration(t))
		rn := "Result" + strings.TrimPrefix(name, "Request")
		rt := ResultType(d.Command)
		defs[rn] = schema(rt)
		fmt.Fprintf(&ts, "export type %s = %s;\n\n", rn, declaration(rt))
	}
	defs["RefusalResult"] = schema(RefusalResultType())
	fmt.Fprintf(&ts, "export type RefusalResult = %s;\n\n", declaration(RefusalResultType()))
	fmt.Fprintf(&ts, "export type MutationRequest = %s;\n", strings.Join(names, " | "))
	ts.WriteString("export type Command = ")
	for i, d := range Commands() {
		if i > 0 {
			ts.WriteString(" | ")
		}
		fmt.Fprintf(&ts, "%q", d.Command)
	}
	ts.WriteString(";\n")
	root := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "Slice01 mutation request boundaries", "$defs": defs, "$comment": "Validate the selected route's $defs entry. This schema is not permission admission. Strict JSON decoding rejects duplicate keys, invalid Unicode and nondecimal numbers before schema validation."}
	var b bytes.Buffer
	e := json.NewEncoder(&b)
	e.SetIndent("", "  ")
	e.SetEscapeHTML(false)
	if err := e.Encode(root); err != nil {
		return nil, err
	}
	return map[string][]byte{"schemas/mutation-requests.schema.json": b.Bytes(), "web/generated/contracts.d.ts": []byte(ts.String())}, nil
}
func typeName(c Command) string {
	var b strings.Builder
	b.WriteString("Request")
	upper := true
	for _, r := range c {
		if r == '.' || r == '-' {
			upper = true
			continue
		}
		if upper && r >= 'a' && r <= 'z' {
			r -= 32
		}
		upper = false
		b.WriteRune(r)
	}
	return b.String()
}
func declaration(t *Type) string {
	if t.Nullable {
		c := *t
		c.Nullable = false
		return "(" + declaration(&c) + " | null)"
	}
	switch t.Kind {
	case "object":
		var b strings.Builder
		b.WriteString("{\n")
		for _, k := range sortedFields(t) {
			f := t.Fields[k]
			fmt.Fprintf(&b, "  readonly %s", k)
			if f.Optional {
				b.WriteByte('?')
			}
			fmt.Fprintf(&b, ": %s;\n", declaration(f.Type))
		}
		b.WriteString("}")
		return b.String()
	case "array":
		return "ReadonlyArray<" + declaration(t.Element) + ">"
	case "integer":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "string":
		if len(t.Enum) == 0 {
			return "string"
		}
		a := make([]string, len(t.Enum))
		for i, e := range t.Enum {
			a[i] = fmt.Sprintf("%q", e)
		}
		return strings.Join(a, " | ")
	default:
		panic("invalid descriptor")
	}
}
func schema(t *Type) map[string]any {
	if t.Nullable {
		c := *t
		c.Nullable = false
		return map[string]any{"anyOf": []any{schema(&c), map[string]any{"type": "null"}}}
	}
	m := map[string]any{"type": t.Kind}
	switch t.Kind {
	case "object":
		p := map[string]any{}
		required := []string{}
		for _, k := range sortedFields(t) {
			f := t.Fields[k]
			p[k] = schema(f.Type)
			if !f.Optional {
				required = append(required, k)
			}
		}
		m["properties"] = p
		m["required"] = required
		m["additionalProperties"] = false
		if t.ExclusiveField != "" {
			ordinary := map[string]any{}
			for k, value := range p {
				if k != t.ExclusiveField {
					ordinary[k] = value
				}
			}
			m["oneOf"] = []any{
				map[string]any{"type": "object", "properties": map[string]any{t.ExclusiveField: p[t.ExclusiveField]}, "required": []string{t.ExclusiveField}, "additionalProperties": false},
				map[string]any{"type": "object", "properties": ordinary, "required": required, "additionalProperties": false},
			}
		}
	case "array":
		m["items"] = schema(t.Element)
		if t.Format == "sorted-unique" {
			m["uniqueItems"] = true
			m["x-order"] = "ASCII ascending"
		}
	case "integer":
		m["minimum"] = t.Min
		m["maximum"] = t.Max
	case "string":
		if len(t.Enum) > 0 {
			m["enum"] = t.Enum
		}
		switch t.Format {
		case "uuid":
			m["pattern"] = uuidPattern.String()
			m["not"] = map[string]any{"const": "00000000-0000-0000-0000-000000000000"}
		case "sha256":
			m["pattern"] = hashPattern.String()
		case "timestamp":
			m["pattern"] = timePattern.String()
			m["format"] = "date-time"
			m["x-year-minimum"] = 1
		case "title":
			m["minLength"] = 1
			m["maxLength"] = 200
			m["x-nonblank"] = true
		case "prose", "comment":
			m["x-max-utf8-bytes"] = 65536
			if t.Format == "comment" {
				m["x-nonblank"] = true
			}
		case "attachment-name":
			m["x-max-utf8-bytes"] = 255
		case "media-label":
			m["maxLength"] = 127
			m["pattern"] = `^[\x00-\x7f]*$`
		}
	}
	return m
}
