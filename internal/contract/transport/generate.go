// GeneratedFiles is pure and returns disjoint paths for the common generator.
// Shared D02 rows reference the C03 artifact; command results reference C01.
func GeneratedFiles() (map[string][]byte, error) {
	defs := map[string]any{}
	var ts strings.Builder
	ts.WriteString("// Code generated by contractgen. DO NOT EDIT.\n// Advisory declarations: Go validation remains authoritative.\n// Secret bodies are ephemeral only; never retained, logged or exported.\nimport type * as Archive from '../archive/contracts';\nimport type * as Mutation from '../contracts';\n\n")
	for _, v := range models {
		t := reflect.TypeOf(v)
		s, declaration := schema(t, true), typescript(t, true)
		if t == reflect.TypeFor[CredentialCLI]() {
			s, declaration = credentialDeclaration()
		}
		if t == reflect.TypeFor[ExportStatus]() {
			s, declaration = exportDeclaration()
		}
		if t == reflect.TypeFor[SessionCodeCLI]() {
			s, declaration = sessionCodeDeclaration()
		}
		defs[t.Name()] = s
		fmt.Fprintf(&ts, "export type %s = %s;\n\n", t.Name(), declaration)
	}
	terminalDeclarations(defs, &ts)
	mutationDeclarations(defs, &ts)
	for own, other := range map[string]string{"PreviewRequest": "PreviewRequest", "Preview": "Preview", "Confirmation": "Confirmation", "RestoreStatus": "Status"} {
		defs[own] = map[string]any{"$ref": "../archive/contracts.schema.json#/$defs/" + other}
	}
	ts.WriteString("export type PreviewRequest = Archive.PreviewRequest;\nexport type Preview = Archive.Preview;\nexport type Confirmation = Archive.Confirmation;\nexport type RestoreStatus = Archive.Status;\nexport type CredentialIssueRequest = CodeRequest;\n")
	defs["CredentialIssueRequest"] = map[string]any{"$ref": "#/$defs/CodeRequest"}
	root := map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "D03 public transport boundaries", "$comment": "Select a $defs entry. Strict Go decoding and cross-field/reference checks are required. Structure is never terminal authenticity. Secret bodies are ephemeral only; no HTTP, auth, storage, multipart or native implementation.", "$defs": defs}
	b, e := json.MarshalIndent(root, "", "  ")
	if e != nil {
		return nil, e
	}
	return map[string][]byte{"schemas/transport/contracts.schema.json": append(b, '\n'), "web/generated/transport/contracts.d.ts": []byte(strings.TrimRight(ts.String(), "\n") + "\n")}, nil
}

func mutationDeclarations(defs map[string]any, ts *strings.Builder) {
	variants := []any{}
	names := []string{}
	for _, d := range contract.Commands() {
		name := "Request" + suffix(d.Command)
		names = append(names, name)
		variants = append(variants, map[string]any{"$ref": "#/$defs/" + name})
		rev := map[string]any{"type": "null"}
		typ := "null"
		if d.Target == "card" {
			rev = schema(reflect.TypeFor[A.Positive](), false)
			typ = "number"
		}
		defs[name] = map[string]any{"allOf": []any{map[string]any{"$ref": "../mutation-requests.schema.json#/$defs/" + name}, map[string]any{"type": "object", "required": []string{"expectedCardRevision"}, "properties": map[string]any{"expectedCardRevision": rev}}}}
		fmt.Fprintf(ts, "export type %s = Omit<Mutation.%s, 'expectedCardRevision'> & { readonly expectedCardRevision: %s };\n\n", name, name, typ)
	}
	defs["MutationRequest"] = map[string]any{"anyOf": variants}
	fmt.Fprintf(ts, "export type MutationRequest = %s;\n\n", strings.Join(names, " | "))
}
func fieldName(f reflect.StructField) string { return strings.Split(f.Tag.Get("json"), ",")[0] }
func fields(t reflect.Type) []reflect.StructField {
	r := make([]reflect.StructField, t.NumField())
	for i := range r {
		r[i] = t.Field(i)
	}
	sort.Slice(r, func(i, j int) bool { return fieldName(r[i]) < fieldName(r[j]) })
	return r
}
func external(t reflect.Type) bool {
	return t.PkgPath() == reflect.TypeFor[A.Identity]().PkgPath() && t.Kind() == reflect.Struct
}
func schema(t reflect.Type, inline bool) map[string]any {
	if t.Kind() == reflect.Pointer {
		return map[string]any{"anyOf": []any{schema(t.Elem(), false), map[string]any{"type": "null"}}}
	}
	if t == reflect.TypeFor[json.RawMessage]() {
		return map[string]any{"type": "object"}
	}
	if external(t) {
		return map[string]any{"$ref": "../archive/contracts.schema.json#/$defs/" + t.Name()}
	}
	if t.Kind() == reflect.Struct && !inline {
		return map[string]any{"$ref": "#/$defs/" + t.Name()}
	}
	switch t.Kind() {
	case reflect.Struct:
		p := map[string]any{}
		required := []string{}
		for _, f := range fields(t) {
			n := fieldName(f)
			typ := f.Type
			optional := t == reflect.TypeFor[NonterminalRefusal]() && f.Name == "OpID"
			if optional {
				typ = typ.Elem()
			} else {
				required = append(required, n)
			}
			p[n] = schema(typ, false)
			if (t == reflect.TypeFor[Error]() || t == reflect.TypeFor[CredentialError]()) && (n == "code" || n == "message") {
				p[n] = map[string]any{"type": "string", "minLength": 1}
			}
			if t == reflect.TypeFor[Error]() && n == "field" {
				p[n] = map[string]any{"anyOf": []any{map[string]any{"type": "string", "pattern": fieldRE.String()}, map[string]any{"type": "null"}}}
			}
			if t == reflect.TypeFor[ExportResult]() && f.Name == "Destination" {
				p[n] = map[string]any{"type": "null"}
			}
		}
		m := map[string]any{"type": "object", "properties": p, "required": required, "additionalProperties": false}
		if t == reflect.TypeFor[Conflict]() {
			m["anyOf"] = []any{map[string]any{"properties": map[string]any{"cardId": map[string]any{"type": "null"}, "cardRevision": map[string]any{"type": "null"}}}, map[string]any{"properties": map[string]any{"cardId": schema(reflect.TypeFor[A.UUID](), false), "cardRevision": schema(reflect.TypeFor[A.Positive](), false)}}}
		}
		return m
	case reflect.Slice:
		if t == reflect.TypeFor[Rights]() {
			return map[string]any{"type": "array", "items": map[string]any{"type": "string", "enum": rights}, "uniqueItems": true, "x-order": "ASCII ascending"}
		}
		return map[string]any{"type": "array", "items": schema(t.Elem(), false)}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Uint64:
		m := map[string]any{"type": "integer", "minimum": 0, "maximum": contract.MaxInteger}
		if t.Name() == "Positive" {
			m["minimum"] = 1
		}
		if t.Name() == "Version" {
			m["const"] = 1
		}
		return m
	case reflect.String:
		m := map[string]any{"type": "string"}
		if e := enums[t.Name()]; len(e) > 0 {
			m["enum"] = e
		}
		switch t.Name() {
		case "UUID":
			m["pattern"] = `^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`
			m["not"] = map[string]any{"const": "00000000-0000-0000-0000-000000000000"}
		case "UUIDv4":
			m["pattern"] = v4RE.String()
		case "Digest":
			m["pattern"] = `^[0-9a-f]{64}$`
		case "Timestamp":
			m["pattern"] = `^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$`
			m["format"] = "date-time"
			m["x-year-minimum"] = 1
		case "Kind":
			m["enum"] = []string{"human", "automation"}
		case "Command":
			a := []string{}
			for _, d := range contract.Commands() {
				a = append(a, string(d.Command))
			}
			m["enum"] = a
		case "SecretCode":
			m["pattern"] = `^[A-Za-z0-9_-]{21}[AQgw]$`
			m["writeOnly"] = true
		case "SecretToken":
			m["pattern"] = `^[A-Za-z0-9_-]{42}[AEIMQUYcgkosw048]$`
			m["writeOnly"] = true
		}
		return m
	}
	panic("unsupported transport type")
}
func typescript(t reflect.Type, inline bool) string {
	if t.Kind() == reflect.Pointer {
		return typescript(t.Elem(), false) + " | null"
	}
	if t == reflect.TypeFor[json.RawMessage]() {
		return "Readonly<Record<string, unknown>>"
	}
	if external(t) {
		return "Archive." + t.Name()
	}
	if t.Kind() == reflect.Struct && !inline {
		return t.Name()
	}
	switch t.Kind() {
	case reflect.Struct:
		var b strings.Builder
		b.WriteString("{\n")
		for _, f := range fields(t) {
			name := fieldName(f)
			typ := f.Type
			optional := ""
			if t == reflect.TypeFor[NonterminalRefusal]() && f.Name == "OpID" {
				optional = "?"
				typ = typ.Elem()
			}
			s := typescript(typ, false)
			if t == reflect.TypeFor[ExportResult]() && f.Name == "Destination" {
				s = "null"
			}
			fmt.Fprintf(&b, "  readonly %s%s: %s;\n", name, optional, s)
		}
		b.WriteString("}")
		return b.String()
	case reflect.Slice:
		if t == reflect.TypeFor[Rights]() {
			return "ReadonlyArray<" + quoted(rights) + ">"
		}
		return "ReadonlyArray<" + typescript(t.Elem(), false) + ">"
	case reflect.Bool:
		return "boolean"
	case reflect.Uint64:
		if t.Name() == "Version" {
			return "1"
		}
		return "number"
	case reflect.String:
		if a := enums[t.Name()]; len(a) > 0 {
			return quoted(a)
		}
		if t.Name() == "Kind" {
			return "'human' | 'automation'"
		}
		return "string"
	}
	panic("unsupported transport type")
}
func quoted(a []string) string {
	b := make([]string, len(a))
	for i, s := range a {
		b[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(b, " | ")
}

func replacedDeclaration(t reflect.Type, override map[string]string) string {
	var b strings.Builder
	b.WriteString("{\n")
	for _, f := range fields(t) {
		n := fieldName(f)
		s, ok := override[n]
		if !ok {
			s = typescript(f.Type, false)
		}
		fmt.Fprintf(&b, "  readonly %s: %s;\n", n, s)
	}
	b.WriteString("}")
	return b.String()
}
func credentialDeclaration() (map[string]any, string) {
	variants := []any{}
	declarations := []string{}
	for _, outcome := range []string{"confirmed", "refused", "failed", "unavailable", "unknown"} {
		commands := []string{"issue", "revoke"}
		if outcome != "confirmed" {
			commands = []string{""}
		}
		for _, command := range commands {
			m := schema(reflect.TypeFor[CredentialCLI](), true)
			p := m["properties"].(map[string]any)
			p["outcome"] = map[string]any{"const": outcome}
			o := map[string]string{"outcome": fmt.Sprintf("%q", outcome)}
			if command != "" {
				p["command"] = map[string]any{"const": command}
				o["command"] = fmt.Sprintf("%q", command)
			}
			if outcome == "confirmed" {
				result := schema(reflect.TypeFor[CredentialResult](), true)
				rp := result["properties"].(map[string]any)
				ro := map[string]string{}
				available := command == "issue"
				rp["locallyAvailable"] = map[string]any{"const": available}
				ro["locallyAvailable"] = fmt.Sprint(available)
				if available {
					for _, f := range fields(reflect.TypeFor[CredentialResult]()) {
						if f.Type.Kind() == reflect.Pointer {
							rp[fieldName(f)] = schema(f.Type.Elem(), false)
							ro[fieldName(f)] = typescript(f.Type.Elem(), false)
						}
					}
				}
				p["result"] = result
				p["error"] = map[string]any{"type": "null"}
				o["result"] = replacedDeclaration(reflect.TypeFor[CredentialResult](), ro)
				o["error"] = "null"
			} else {
				p["error"] = schema(reflect.TypeFor[CredentialError](), false)
				o["error"] = "CredentialError"
			}
			variants = append(variants, m)
			declarations = append(declarations, replacedDeclaration(reflect.TypeFor[CredentialCLI](), o))
		}
	}
	return map[string]any{"oneOf": variants}, strings.Join(declarations, " | ")
}
func exportDeclaration() (map[string]any, string) {
	variants := []any{}
	declarations := []string{}
	for _, outcome := range []string{"confirmed", "offered", "failed", "unknown"} {
		m := schema(reflect.TypeFor[ExportStatus](), true)
		p := m["properties"].(map[string]any)
		p["outcome"] = map[string]any{"const": outcome}
		o := map[string]string{"outcome": fmt.Sprintf("%q", outcome)}
		if outcome == "confirmed" || outcome == "offered" {
			result := schema(reflect.TypeFor[ExportResult](), true)
			rp := result["properties"].(map[string]any)
			rp["sourceIdentity"] = schema(reflect.TypeFor[A.Identity](), false)
			rp["sourceRevision"] = schema(reflect.TypeFor[A.Number](), false)
			p["result"] = result
			o["result"] = "{ readonly sourceIdentity: Archive.Identity; readonly sourceRevision: number; readonly destination: null }"
		}
		variants = append(variants, m)
		declarations = append(declarations, replacedDeclaration(reflect.TypeFor[ExportStatus](), o))
	}
	return map[string]any{"oneOf": variants}, strings.Join(declarations, " | ")
}
func suffix(c contract.Command) string {
	var b strings.Builder
	upper := true
	for _, r := range c {
		if r == '.' || r == '-' {
			upper = true
			continue
		}
		if upper && r >= 'a' && r <= 'z' {
			r -= 32
		}
		upper = false
		b.WriteRune(r)
	}
	return b.String()
}
func terminalDeclarations(defs map[string]any, ts *strings.Builder) {
	variants := []any{}
	names := []string{}
	for _, d := range contract.Commands() {
		for _, outcome := range []string{"committed", "not_committed"} {
			for _, retention := range []string{"full", "compact"} {
				name := "Terminal" + suffix(d.Command) + strings.ReplaceAll(strings.Title(outcome), "_", "") + strings.Title(retention)
				m := schema(reflect.TypeFor[Terminal](), true)
				p := m["properties"].(map[string]any)
				p["command"] = map[string]any{"const": string(d.Command)}
				p["outcome"] = map[string]any{"const": outcome}
				p["retention"] = map[string]any{"const": retention}
				targetTS := "null"
				targetSchema := map[string]any{"type": "null"}
				cardPreTS := "null"
				cardPreSchema := map[string]any{"type": "null"}
				if d.Target != "none" {
					key := "cardId"
					if d.Target == "grant" {
						key = "grantId"
					}
					targetSchema = map[string]any{"type": "object", "properties": map[string]any{key: schema(reflect.TypeFor[A.UUID](), false)}, "required": []string{key}, "additionalProperties": false}
					targetTS = "{ readonly " + key + ": string }"
				}
				if d.Target == "card" {
					cardPreSchema = schema(reflect.TypeFor[A.Positive](), false)
					cardPreTS = "number"
				}
				p["target"] = targetSchema
				p["expectedCardRevision"] = cardPreSchema
				revTS := "null"
				cardTS := "null"
				codeTS := "string"
				p["revision"] = map[string]any{"type": "null"}
				p["cardRevision"] = map[string]any{"type": "null"}
				if outcome == "committed" {
					p["revision"] = schema(reflect.TypeFor[A.Positive](), false)
					revTS = "number"
					p["code"] = map[string]any{"const": "OK"}
					codeTS = "'OK'"
					if d.Target == "card" || d.Command == "card.create" {
						p["cardRevision"] = schema(reflect.TypeFor[A.Positive](), false)
						cardTS = "number"
					}
				} else {
					p["code"] = map[string]any{"type": "string", "minLength": 1, "not": map[string]any{"const": "OK"}}
					p["resultRefs"] = map[string]any{"type": "array", "maxItems": 0}
				}
				resultTS := "null"
				removalTS := "Archive.Removal"
				p["result"] = map[string]any{"type": "null"}
				p["removal"] = schema(reflect.TypeFor[A.Removal](), false)
				if retention == "full" {
					removalTS = "null"
					p["removal"] = map[string]any{"type": "null"}
					if outcome == "committed" {
						resultTS = "Mutation.Result" + suffix(d.Command)
						p["result"] = map[string]any{"$ref": "../mutation-requests.schema.json#/$defs/Result" + suffix(d.Command)}
					} else {
						resultTS = "RefusalResult"
						p["result"] = map[string]any{"$ref": "#/$defs/RefusalResult"}
					}
				}
				want := 0
				if d.Command == "attachment.add" {
					want = 1
				}
				p["byteFacts"] = map[string]any{"type": "array", "items": schema(reflect.TypeFor[A.ByteFact](), false), "minItems": want, "maxItems": want}
				defs[name] = m
				variants = append(variants, map[string]any{"$ref": "#/$defs/" + name})
				names = append(names, name)
				replacements := map[string]string{"command": fmt.Sprintf("%q", d.Command), "outcome": fmt.Sprintf("%q", outcome), "retention": fmt.Sprintf("%q", retention), "target": targetTS, "expectedCardRevision": cardPreTS, "revision": revTS, "cardRevision": cardTS, "code": codeTS, "result": resultTS, "removal": removalTS}
				var b strings.Builder
				b.WriteString("{\n")
				for _, f := range fields(reflect.TypeFor[Terminal]()) {
					key := fieldName(f)
					s, ok := replacements[key]
					if !ok {
						s = typescript(f.Type, false)
					}
					if key == "resultRefs" && outcome == "not_committed" {
						s = "readonly []"
					}
					fmt.Fprintf(&b, "  readonly %s: %s;\n", key, s)
				}
				b.WriteString("}")
				fmt.Fprintf(ts, "export type %s = %s;\n\n", name, b.String())
			}
		}
	}
	defs["Terminal"] = map[string]any{"oneOf": variants}
	fmt.Fprintf(ts, "export type Terminal = %s;\n\n", strings.Join(names, " | "))
}
