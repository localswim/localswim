const maxBody = 4096

var errInvalidMutation = errors.New("invalid grant mutation")

func bearer(r *http.Request) (T.SecretToken, bool) {
	v := r.Header.Values("Authorization")
	if len(v) != 1 || !strings.HasPrefix(v[0], "Bearer ") {
		return "", false
	}
	t := strings.TrimPrefix(v[0], "Bearer ")
	return T.SecretToken(t), len(t) == 43 && !strings.ContainsAny(t, " \t\r\n,")
}

func refuse(w http.ResponseWriter, status int, code string) {
	respond(w, status, T.NonterminalRefusal{APIVersion: 1, Outcome: "refused", Error: T.Error{Code: code, Message: "Request refused"}})
}
func respond(w http.ResponseWriter, status int, value any) {
	b, err := T.Readable(value)
	if err != nil {
		status = 503
		b, _ = T.Readable(T.NonterminalRefusal{APIVersion: 1, Outcome: "refused", Error: T.Error{Code: "UNAVAILABLE", Message: "Request refused"}})
	}
	w.Header().Set("Cache-Control", "no-store")
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_, _ = w.Write(b)
}
func result(w http.ResponseWriter, r writer.Result, newCommit bool) {
	if r.Terminal != nil && r.Unknown == nil && r.Refused == nil {
		status := 200
		if newCommit && r.Terminal.Outcome == "committed" && r.Terminal.Command == "grant.create" {
			status = 201
		}
		respond(w, status, *r.Terminal)
		return
	}
	if r.Unknown != nil && r.Terminal == nil && r.Refused == nil {
		respond(w, 503, *r.Unknown)
		return
	}
	if r.Refused != nil && r.Terminal == nil && r.Unknown == nil {
		status := 403
		switch r.Refused.Error.Code {
		case "INVALID_INPUT":
			status = 400
		case "UNAUTHENTICATED":
			status = 401
		case "NOT_FOUND":
			status = 404
		case "OPERATION_MISMATCH", "REVISION_CONFLICT", "INCARNATION_CONFLICT":
			status = 409
		case "UNAVAILABLE":
			status = 503
		}
		respond(w, status, *r.Refused)
		return
	}
	refuse(w, 503, "UNAVAILABLE")
}

// A callback running is insufficient proof of a fresh commit: it may roll back
// before a competing identical submission commits a different generated grant.
// Only the exact ID generated by this invocation can justify HTTP 201.
func freshCreate(r writer.Result, created string) bool {
	if created == "" || r.Terminal == nil || r.Terminal.Command != "grant.create" || r.Terminal.Outcome != "committed" {
		return false
	}
	for _, ref := range r.Terminal.ResultRefs {
		if ref.Kind == "grant" && string(ref.ID) == created {
			return true
		}
	}
	return false
}

// bodyScope parses the strict JSON syntax before extracting only the board
// selector. Complete field/type validation and actor binding are C02's job.
func bodyScope(w http.ResponseWriter, r *http.Request) ([]byte, string, int) {
	b, err := io.ReadAll(http.MaxBytesReader(w, r.Body, maxBody))
	if err != nil {
		if _, ok := err.(*http.MaxBytesError); ok {
			return nil, "", 413
		}
		return nil, "", 400
	}
	v, err := contract.DecodeJSON(b)
	if err != nil {
		return nil, "", 400
	}
	m, ok := v.(map[string]any)
	if !ok {
		return nil, "", 400
	}
	board, ok := m["boardId"].(string)
	if !ok {
		return nil, "", 400
	}
	return b, board, 0
}

type readAccess struct {
	ctx  context.Context
	conn *sql.Conn
}

func (a readAccess) Scan(q string, args []any, dest ...any) error {
	return a.conn.QueryRowContext(a.ctx, q, args...).Scan(dest...)
}
func (a readAccess) Query(q string, args ...any) (*sql.Rows, error) {
	return a.conn.QueryContext(a.ctx, q, args...)
}

// resolve binds revoke scope to the stored grant, even when disabled. Enabled
// admission and all mutable authority remain G01/S02 checks in their snapshot.
func resolve(r writer.Read, command contract.Command, target, submitted string) (grants.Route, error) {
	var b, i string
	var err error
	if command == "grant.revoke" {
		err = r.Scan("SELECT b.board_id,g.incarnation FROM grant_record g JOIN board b ON b.incarnation=g.incarnation WHERE b.singleton=1 AND g.grant_id=?", []any{target}, &b, &i)
	} else {
		err = r.Scan("SELECT board_id,incarnation FROM board WHERE singleton=1", nil, &b, &i)
	}
	if err != nil {
		return grants.Route{}, err
	}
	if b != submitted {
		return grants.Route{}, grants.ErrDenied
	}
	return grants.Route{BoardID: b, Incarnation: i, GrantID: target}, nil
}

func (h *Handler) owner(w http.ResponseWriter, r *http.Request, command contract.Command, target string, token T.SecretToken) {
	b, board, status := bodyScope(w, r)
	if status != 0 {
		code := "INVALID_INPUT"
		if status == 413 {
			code = "INPUT_TOO_LARGE"
		}
		refuse(w, status, code)
		return
	}
	var intent contract.Intent
	var route grants.Route
	err := h.native.WithNativeSnapshot(r.Context(), token, func(actor string, rd writer.Read) error {
		var err error
		intent, err = T.FreezeMutation(b, contract.ResolvedRoute{Command: command, BoardID: board, TargetID: target}, contract.AuthenticatedActor{ActorID: actor})
		if err != nil {
			return errInvalidMutation
		}
		route, err = resolve(rd, command, target, board)
		return err
	})
	if err != nil {
		if errors.Is(err, credentials.ErrDenied) {
			refuse(w, 401, "UNAUTHENTICATED")
		} else if errors.Is(err, errInvalidMutation) {
			refuse(w, 400, "INVALID_INPUT")
		} else if errors.Is(err, sql.ErrNoRows) {
			refuse(w, 404, "NOT_FOUND")
		} else if errors.Is(err, grants.ErrDenied) {
			refuse(w, 403, "FORBIDDEN")
		} else {
			refuse(w, 503, "UNAVAILABLE")
		}
		return
	}
	id, _, _, _, _, err := intent.Context()
	if err != nil {
		refuse(w, 400, "INVALID_INPUT")
		return
	}
	if id.Incarnation != route.Incarnation {
		o, err := outcome.Base(intent)
		if err != nil {
			refuse(w, 400, "INVALID_INPUT")
			return
		}
		respond(w, 503, T.KnownIdentityUnknown{APIVersion: 1, Outcome: "unknown", BoardID: o.Origin.BoardID, Incarnation: o.Origin.Incarnation, OpID: o.OpID, ActorID: o.ActorID, FingerprintVersion: 1, Fingerprint: o.Fingerprint, Error: T.Error{Code: "SOURCE_AUTHORITY_UNAVAILABLE", Message: "Original outcome is unavailable"}})
		return
	}
	out, fresh := h.native.SubmitNativeObserved(r.Context(), token, intent, route)
	if out.Result != nil {
		result(w, *out.Result, fresh)
		return
	}
	if out.Preparation == credentials.Refused {
		refuse(w, 401, "UNAUTHENTICATED")
		return
	}
	// Attribution preparation and a grant outcome are distinct. Preparation
	// failure/uncertainty supplies no terminal grant proof and is never replayed.
	o, err := outcome.Base(intent)
	if err != nil {
		refuse(w, 503, "UNAVAILABLE")
		return
	}
	respond(w, 503, T.KnownIdentityUnknown{APIVersion: 1, Outcome: "unknown", BoardID: o.Origin.BoardID, Incarnation: o.Origin.Incarnation, OpID: o.OpID, ActorID: o.ActorID, FingerprintVersion: 1, Fingerprint: o.Fingerprint, Error: T.Error{Code: "OUTCOME_UNKNOWN", Message: "Original outcome is unavailable"}})
}

func (h *Handler) ordinary(w http.ResponseWriter, r *http.Request, command contract.Command, target string) {
	mode, token, ok := H.Credential(r.Context())
	if !ok {
		refuse(w, 401, "UNAUTHENTICATED")
		return
	}
	current, err := h.sessions.Current(r.Context(), mode, token)
	if err != nil {
		refuse(w, 401, "UNAUTHENTICATED")
		return
	}
	b, board, status := bodyScope(w, r)
	if status != 0 {
		code := "INVALID_INPUT"
		if status == 413 {
			code = "INPUT_TOO_LARGE"
		}
		refuse(w, status, code)
		return
	}
	// This early check compares authenticated source scope, not a rights policy.
	if board != string(current.Grant.BoardID) {
		refuse(w, 403, "FORBIDDEN")
		return
	}
	a, err := h.sessions.Admission(mode, token)
	if err != nil {
		refuse(w, 401, "UNAUTHENTICATED")
		return
	}
	i, err := T.FreezeMutation(b, contract.ResolvedRoute{Command: command, BoardID: board, TargetID: target}, contract.AuthenticatedActor{ActorID: string(current.ActorID)})
	if err != nil {
		refuse(w, 400, "INVALID_INPUT")
		return
	}
	ctx, cancel := context.WithTimeout(r.Context(), 10*time.Second)
	defer cancel()
	l, err := h.store.Reader(ctx)
	if err != nil {
		refuse(w, 503, "UNAVAILABLE")
		return
	}
	var route grants.Route
	err = l.Do(ctx, func(c *sql.Conn) error {
		if _, err := c.ExecContext(ctx, "BEGIN"); err != nil {
			return err
		}
		rd := readAccess{ctx, c}
		if err := a.Require(ctx, rd, string(current.Grant.BoardID), string(current.Grant.Incarnation), string(current.ActorID)); err != nil {
			return err
		}
		var e error
		route, e = resolve(rd, command, target, board)
		if e != nil {
			return e
		}
		_, e = c.ExecContext(ctx, "COMMIT")
		return e
	})
	closeErr := l.Close()
	if err != nil || closeErr != nil {
		if err == sql.ErrNoRows {
			refuse(w, 404, "NOT_FOUND")
		} else if err == grants.ErrDenied {
			refuse(w, 403, "FORBIDDEN")
		} else {
			refuse(w, 503, "UNAVAILABLE")
		}
		return
	}
	cb := a.GrantCallbacks(route)
	apply := cb.Apply
	created := ""
	cb.Apply = func(ctx context.Context, w writer.Write, i contract.Intent, atTimestamp A.Timestamp) (writer.Effect, error) {
		effect, err := apply(ctx, w, i, atTimestamp)
		if err == nil && i.Command() == "grant.create" {
			for _, ref := range effect.References {
				if ref.Kind == "grant" {
					created = string(ref.ID)
				}
			}
		}
		return effect, err
	}
	out := writer.New(h.store).Submit(r.Context(), i, cb)
	result(w, out, freshCreate(out, created))
}
