//go:build windows && amd64 && v02qualification

package main

type fixtureStageFailure string

func (e fixtureStageFailure) Error() string { return string(e) }
func fixtureFailure(code string) error      { return fixtureStageFailure(code) }
func fixtureDiagnostic(e error) string {
	v, ok := e.(fixtureStageFailure)
	if !ok {
		return "V02_UNAVAILABLE"
	}
	switch string(v) {
	case "V02_DELEGATION_CONSOLE_REQUIRED", "V02_DELEGATION_DISPLAY_UNAVAILABLE", "V02_DELEGATION_INPUT_UNAVAILABLE", "V02_DELEGATION_LINE_MISMATCH", "V02_SETUP_CONTEXT_UNAVAILABLE", "V02_TRUST_UNAVAILABLE", "V02_HUMAN_SOURCE_UNAVAILABLE", "V02_HUMAN_GRANT_UNAVAILABLE", "V02_DELEGATION_CONTEXT_MISMATCH", "V02_HTTPS_UNAVAILABLE", "V02_SOURCE_OPEN_UNAVAILABLE", "V02_NATIVE_SOURCE_UNAVAILABLE", "V02_SESSION_UNAVAILABLE", "V02_ASSETS_UNAVAILABLE", "V02_ROUTES_UNAVAILABLE", "V02_PIPE_ACCOUNT_UNAVAILABLE", "V02_PIPE_DESCRIPTOR_UNAVAILABLE", "V02_PIPE_CREATE_UNAVAILABLE", "V02_PIPE_EVENT_UNAVAILABLE", "V02_PIPE_CONNECT_UNAVAILABLE", "V02_PIPE_DEADLINE_UNAVAILABLE":
		return string(v)
	}
	return "V02_UNAVAILABLE"
}
