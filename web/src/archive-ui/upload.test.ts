import type { BoardRead, SessionRead } from "../../generated/transport/contracts.js";
import type { OriginalOutcome } from "../api/client.js";
import { configuredWorkflowFixture } from "../board/workflow.test.js";
import { mountSyntheticBoard } from "../board/view.test.js";
import { ArchiveView } from "./view.js";

// Controlled DOM evidence. The native/browser suite separately proves delivery,
// refusal atomicity, quotas, byte preservation and runnable restore conservation.
export async function runAttachmentUploadProbe(input: BoardRead, session: SessionRead): Promise<number> {
  const fixture = await mountSyntheticBoard(input, session); fixture.view.destroy();
  const root = document.createElement("main"); document.body.replaceChildren(root);
  let checks = 0, sends = 0, lookups = 0, mode: OriginalOutcome["state"] = "unsent";
  let lastIntent: Parameters<typeof fixture.client.submitAttachment>[0] | undefined;
  let release: (() => void) | undefined;
  const check = (condition: unknown, message: string): void => { if (!condition) throw Error(message); checks++; };
  const settle = async (): Promise<void> => { for (let i = 0; i < 25; i++) await new Promise(resolve => setTimeout(resolve, 0)); };
  fixture.client.submitAttachment = async (intent, announce) => {
    sends++; lastIntent = intent;
    const outcome = { opId: intent.request.opId, state: mode, message: "Synthetic " + mode };
    announce(outcome); return outcome;
  };
  fixture.client.lookup = async (_context, opId) => { lookups++; return { opId, state: "not_committed", message: "Synthetic terminal refusal" }; };
  const view = new ArchiveView(root, fixture.client, fixture.board.result.identity.boardId);
  const button = (text: string): HTMLButtonElement => [...root.querySelectorAll("button")].find(node => node.textContent === text)!;
  const field = (): HTMLInputElement => root.querySelector<HTMLInputElement>('input[type="file"]')!;
  const source = (): string => root.querySelector('[aria-label="Captured attachment source"]')!.textContent!;
  const name = (): HTMLInputElement => root.querySelector<HTMLInputElement>('form input:not([type="file"])')!;
  const choose = (file?: File): void => {
    const transfer = new DataTransfer(); if (file) transfer.items.add(file);
    field().files = transfer.files; field().dispatchEvent(new Event("change", { bubbles: true }));
  };
  try {
    await view.refresh(); button("Open attachment editor").click();
    check(source() === "No complete file captured.", "Empty editor implies a captured file");
    name().value = "Exact metadata 雪"; name().dispatchEvent(new Event("input", { bubbles: true }));
    choose(new File([new Uint8Array([0, 255, 1])], "source.bin")); await settle(); await view.flushPrivateInput();
    check(!button("Attach once").disabled && name().value === "Exact metadata 雪" && source() === "Using file source.bin · 3 bytes", "Capture overwrote deliberate metadata");
    choose(); await settle();
    check(!button("Attach once").disabled && !view.canLeave && source() === "Using file source.bin · 3 bytes", "Cancelled chooser discarded a complete capture");
    const broken = new File(["broken"], "broken.bin"); Object.defineProperty(broken, "arrayBuffer", { value: async () => { throw Error("Synthetic read failure"); } });
    choose(broken); await settle(); check(!button("Attach once").disabled && source() === "Using file source.bin · 3 bytes", "Read failure discarded a complete capture");
    const oversized = new File([], "large.bin"); Object.defineProperty(oversized, "size", { value: 10485761 });
    choose(oversized); await settle(); check(!button("Attach once").disabled && source() === "Using file source.bin · 3 bytes", "Oversize replacement discarded a complete capture");
    button("Attach once").click(); await settle();
    check(sends === 1 && [...new Uint8Array(lastIntent!.bytes)].join() === "0,255,1" && lastIntent!.request.input.name === "Exact metadata 雪", "Failed or cancelled replacement changed retained bytes/metadata");
    const slow = new File(["late"], "late.bin"); Object.defineProperty(slow, "arrayBuffer", { value: () => new Promise<ArrayBuffer>(resolve => { release = () => resolve(new TextEncoder().encode("late").buffer); }) });
    choose(slow); check(button("Attach once").disabled && source() === "Using file source.bin · 3 bytes", "In-flight capture remained dispatchable");
    choose(new File([], "empty.bin")); await settle(); release!(); await settle();
    check(!button("Attach once").disabled && source() === "Using file empty.bin · 0 bytes", "Latest complete selection unavailable");
    const form = root.querySelector("form")!;
    form.dispatchEvent(new CompositionEvent("compositionstart", { bubbles: true }));
    button("Attach once").click(); check(sends === 1 && button("Attach once").disabled, "Composition dispatched upload");
    const enter = new KeyboardEvent("keydown", { key: "Enter", isComposing: true, bubbles: true, cancelable: true }); form.dispatchEvent(enter);
    check(enter.defaultPrevented, "Composition Enter was not prevented");
    form.dispatchEvent(new CompositionEvent("compositionend", { bubbles: true }));
    form.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true })); check(sends === 1, "Implicit form submit dispatched upload");
    button("Attach once").click(); await settle();
    check(sends === 2 && lastIntent!.bytes.byteLength === 0 && lastIntent!.request.input.name === "Exact metadata 雪", "Late capture replaced exact empty bytes or metadata");
    check(!view.canLeave && !button("Attach once").disabled, "Preparation failure released input guard");
    mode = "not_committed"; button("Attach once").click(); await settle();
    check(sends === 3 && !view.canLeave && button("Attach once").disabled, "Terminal refusal released input or auto-enabled replay");
    const retainedName = name(); await view.refresh(); button("Open attachment editor").click();
    check(name() === retainedName && sends === 3, "Refresh/reopen replaced refused input or replayed upload");
    view.discardInput(); button("Open attachment editor").click(); choose(new File(["next"], "next.bin")); await settle();
    mode = "unknown"; button("Attach once").click(); await settle();
    const original = lastIntent!; await view.refresh(); button("Attach once").click(); await settle();
    check(sends === 4 && lookups === 0 && !view.canLeave, "Unknown operation replayed, auto-looked-up or released input");
    button("Look up original attachment operation").click(); await settle();
    check(lookups === 1 && sends === 4 && lastIntent === original && !view.canLeave, "Original lookup replaced operation or released refused input");
    view.discardInput();
    await view.refresh(); button("Open attachment editor").click(); choose(new File(["committed"], "committed.bin")); await settle();
    mode = "committed"; button("Attach once").click(); await settle(); await view.flushPrivateInput();
    check(view.canLeave, "Unchanged successful upload did not release navigation");
    await view.refresh(); choose();
    check(view.canLeave, "Cancelled chooser invalidated the unchanged committed editor");
    const committedFile = field(), committedName = name();
    const afterCommit = new File(["replacement"], "replacement.bin");
    Object.defineProperty(afterCommit, "arrayBuffer", { value: () => new Promise<ArrayBuffer>(resolve => { release = () => resolve(new TextEncoder().encode("replacement").buffer); }) });
    choose(afterCommit);
    check(!view.canLeave && source() === "Using file committed.bin · 9 bytes", "New pending selection retained previous commit navigation release");
    check(!await view.flushPrivateInput(), "Pending file selection passed the private flush navigation guard");
    button("Open attachment editor").click();
    check(field() === committedFile && name() === committedName && field().files?.[0]?.name === "replacement.bin", "Reopening replaced pending file selection after commit");
    release!(); await settle(); await view.flushPrivateInput();
    check(!view.canLeave && !button("Attach once").disabled && source() === "Using file replacement.bin · 11 bytes", "Resolved replacement lost its navigation guard or remained unavailable");
    choose(afterCommit); view.discardInput();
    check(view.canLeave, "Explicit discard did not release pending replacement navigation guard");
    release!(); await settle();
    check(!root.querySelector("form") && !root.querySelector('[aria-label="Captured attachment source"]') && view.canLeave, "Late capture restored explicitly discarded input");
    const workflow = configuredWorkflowFixture(), board = structuredClone(fixture.board), auth = structuredClone(fixture.auth);
    Object.assign(board.result, { workflow });
    board.result.cards.forEach((card, index) => Object.assign(card, { archived: index === 0, lane: workflow.lanes.find(lane => lane.role === (index === 1 ? "completed" : "initial"))!.id }));
    fixture.client.board = async () => board; fixture.client.session = async () => auth;
    await view.refresh();
    const targets = root.querySelector<HTMLSelectElement>('[aria-label="Attachment target card"]')!;
    check(![...targets.options].some(option => option.value === board.result.cards[0]!.cardId || option.value === board.result.cards[1]!.cardId), "Default selector exposed archived or configured Completed card");
    const archived = root.querySelector<HTMLSelectElement>('[aria-label="Attachment archive context"]')!; archived.value = "archived"; archived.dispatchEvent(new Event("change"));
    check(targets.value === board.result.cards[0]!.cardId && !button("Open attachment editor").disabled, "Explicit archived context unavailable");
    button("Open attachment editor").click(); check(root.textContent!.includes("Archived context"), "Frozen editor omitted archived context");
    choose(new File([], "archived.bin")); await settle();
    Object.assign(board.result.cards[0]!, { lane: workflow.lanes.find(lane => lane.role === "completed")!.id }); await view.refresh();
    check(button("Attach once").disabled && !view.canLeave, "Current Completed role left the retained editor dispatchable");
    Object.assign(board.result.cards[0]!, { lane: workflow.lanes.find(lane => lane.role === "initial")!.id }); await view.refresh();
    Object.assign(workflow.actorRights, { [auth.kind]: workflow.actorRights[auth.kind].filter(right => right !== "attach") }); await view.refresh();
    check(button("Open attachment editor").disabled && button("Attach once").disabled && !view.canLeave, "Workflow attach ceiling bypassed or retained input lost");
    return checks;
  } finally { release?.(); view.destroy(); fixture.client.close(); }
}
